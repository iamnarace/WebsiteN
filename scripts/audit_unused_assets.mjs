import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('..', import.meta.url)));
const textExtensions = new Set(['.html', '.css', '.js', '.json', '.md', '.txt', '.xml']);
const ignoredDirectories = new Set(['.git', '.superpowers', '.worktrees']);

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (ignoredDirectories.has(entry.name)) return [];
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

const files = walk(root);
const corpus = files
  .filter((path) => textExtensions.has(extname(path).toLowerCase()))
  .map((path) => readFileSync(path, 'utf8'))
  .join('\n');
const candidates = files
  .filter((path) => relative(root, path).replaceAll('\\', '/').startsWith('assets/'))
  .filter((path) => {
    const repositoryPath = relative(root, path).replaceAll('\\', '/');
    return !corpus.includes(repositoryPath) && !corpus.includes(repositoryPath.replace(/^assets\//, ''));
  })
  .sort((left, right) => statSync(right).size - statSync(left).size);

const lines = [
  '# Asset Audit',
  '',
  'Generated by `node scripts/audit_unused_assets.mjs`.',
  '',
  '## Unreferenced candidates',
  '',
  'Candidates only; they are not automatically deleted.',
  '',
  ...candidates.map((path) => {
    const repositoryPath = relative(root, path).replaceAll('\\', '/');
    return `- \`${repositoryPath}\` — ${(statSync(path).size / 1024).toFixed(1)} KB`;
  }),
  '',
  '## Confirmed removed artifacts',
  '',
  '- `favicon.svg.txt` — replaced by `favicon.svg`.',
  '- `social-share.svg.txt` — replaced by the production PNG.',
  '- `README.md.txt` — duplicate text export; canonical `README.md` remains.',
  '- `README-UPDATE.txt` — obsolete handoff note.',
];

writeFileSync(join(root, 'docs', 'asset-audit.md'), `${lines.join('\n')}\n`);
